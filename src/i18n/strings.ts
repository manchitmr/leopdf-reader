export type Lang = "en" | "si" | "ta";

export const LANGUAGES: Record<Lang, { label: string; strings: Record<StringKey, string> }> = {
  en: { label: "English", strings: en },
  si: { label: "සිංහල", strings: si },
  ta: { label: "தமிழ்", strings: ta },
};

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  const template = LANGUAGES[lang].strings[key] || en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (vars && name in vars ? String(vars[name]) : match));
}

export function detectLang(navigatorLanguage: string): Lang {
  const l = navigatorLanguage.toLowerCase();
  if (l.startsWith("si")) return "si";
  if (l.startsWith("ta")) return "ta";
  return "en";
}
