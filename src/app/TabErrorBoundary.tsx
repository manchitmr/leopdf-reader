import { Component, type ReactNode } from "react";

/** Contains a rendering crash to one document tab instead of blanking the whole window. */
export class TabErrorBoundary extends Component<{ fallback: ReactNode; children: ReactNode }, { failed: boolean }> {
  state = { failed: false };

  static getDerivedStateFromError() {
    return { failed: true };
  }

  render() {
    return this.state.failed ? this.props.fallback : this.props.children;
  }
}
